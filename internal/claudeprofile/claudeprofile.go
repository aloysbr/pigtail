// Package claudeprofile holds the machine-wide table of Claude Code cells.
//
// A cell binds a short id (mt, t, mp, p) to a Claude config dir — the value of
// CLAUDE_CONFIG_DIR, which is what selects the account — and to a scope (perso,
// globex…, declared in scopes.yaml), which decides whether two cells are
// interchangeable for a session. The scope is read canonical: an alias (gx)
// becomes its scope's name, an undeclared value stays as written, lower-cased.
//
// Each cell also carries its cwd_home — the directory its launcher starts in —
// so a directory can be mapped to the scope it belongs to (longest home wins).
//
// The table is generated by the launcher tooling from its own source of truth; pigtail
// only reads it, so nothing here reaches outside the pigtail config dir.
package claudeprofile

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/aloysbr/pigtail/internal/claudeusage"
	"github.com/aloysbr/pigtail/internal/scope"
)

// Filename is the table's name inside the pigtail config dir.
const Filename = "claude-cells.yaml"

// Cell is one account × scope pair. Account is the account letter the launcher
// copies from the launcher config (a, b, c…): a display label only, the account
// itself is the accountUuid read from the cell's .claude.json. Empty when the
// table predates the key. Rank is the cell's 0-based declaration index in
// the launcher config: pigtail usage lists an account at its first
// declared cell. nil when the table predates the key.
type Cell struct {
	ID        string `yaml:"-"`
	ConfigDir string `yaml:"config_dir"`
	Scope     string `yaml:"scope"`
	Account   string `yaml:"account"`
	Rank      *int   `yaml:"rank"`
	// CwdHome is the directory the cell's launcher starts in (a launcher setting,
	// cwd_home); ~ expanded. spawn reads it to tell
	// which scope a directory belongs to (longest home wins). "" when the
	// table predates the key.
	CwdHome string `yaml:"cwd_home"`
	// SelectPct / SwitchPct are the account's usage thresholds (a launcher setting,
	// per account): selection ceiling and
	// anticipatory-switch threshold. nil = pigtail's default
	// (claudeusage.ResolveThresholds).
	SelectPct *float64 `yaml:"select_pct"`
	SwitchPct *float64 `yaml:"switch_pct"`
	// BudgetPct is the account's weekly token budget, as a percent of its 7-day
	// window (per account). nil =
	// pigtail's default (claudeusage.ResolveBudgetPct). Only Staffing reads it.
	BudgetPct *float64 `yaml:"budget_pct"`
}

// UsageInput is the cell as claudeusage reads it (every field copied).
func (c Cell) UsageInput() claudeusage.CellInput {
	return claudeusage.CellInput{ID: c.ID, ConfigDir: c.ConfigDir, Scope: c.Scope, Account: c.Account,
		Rank: c.Rank, SelectPct: c.SelectPct, SwitchPct: c.SwitchPct, BudgetPct: c.BudgetPct}
}

// Table is the parsed cell table.
type Table struct {
	Cells map[string]Cell `yaml:"cells"`
}

// Load reads the cell table from the given pigtail config dir.
func Load(dir string) (*Table, error) {
	path := filepath.Join(dir, Filename)
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w — no Claude cell table; see docs/CONFIG.md § claude-cells.yaml", path, err)
	}
	var t Table
	if err := yaml.Unmarshal(b, &t); err != nil {
		return nil, fmt.Errorf("parse %s: %w", path, err)
	}
	for id, c := range t.Cells {
		c.ID = id
		c.ConfigDir = expandHome(c.ConfigDir)
		c.CwdHome = expandHome(c.CwdHome)
		c.Scope = string(scope.Canonical(c.Scope))
		t.Cells[id] = c
	}
	return &t, nil
}

// Cell returns the cell with the given id.
func (t *Table) Cell(id string) (Cell, bool) {
	if t == nil {
		return Cell{}, false
	}
	c, ok := t.Cells[id]
	return c, ok
}

// ByConfigDir returns the cell owning the given config dir, compared cleaned
// and with ~ expanded like ScopeOf: the relay registry and the scope a session
// speaks for must name the same cell for the same dir, however it is spelt.
func (t *Table) ByConfigDir(path string) (Cell, bool) {
	if t == nil || path == "" {
		return Cell{}, false
	}
	want := filepath.Clean(expandHome(path))
	for _, c := range t.Cells {
		if filepath.Clean(expandHome(c.ConfigDir)) == want {
			return c, true
		}
	}
	return Cell{}, false
}

// ScopeOf returns the scope (gx, perso) of the cell owning configDir. The
// dir is compared cleaned and with ~ expanded, so "~/.claude-perso/" names the
// same cell as its absolute spelling. ok=false when no cell owns it — the bare
// ~/.claude, or no table at all — and the caller decides the fallback.
func (t *Table) ScopeOf(configDir string) (scope string, ok bool) {
	if t == nil || configDir == "" {
		return "", false
	}
	c, ok := t.ByConfigDir(configDir)
	return c.Scope, ok
}

// ConfigDirs lists every known config dir, for transcript lookups, ordered by
// cell id.
//
// The order is part of the contract, not an implementation detail: callers
// resolve a session's account by taking the first config dir that hosts its
// transcript, so a table walked in Go's randomized map order would report a
// different account for the same session between two consecutive runs — the
// exact state eight hand-migrated sessions were left in on 2026-08-12, each
// present in two config dirs at once. Sorting by cell id makes the answer
// stable and explainable ("the alphabetically first cell wins"); it does not
// make an ambiguous session unambiguous, which is claudesession.Find's job.
func (t *Table) ConfigDirs() []string {
	if t == nil {
		return nil
	}
	ids := make([]string, 0, len(t.Cells))
	for id := range t.Cells {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	out := make([]string, 0, len(ids))
	for _, id := range ids {
		out = append(out, t.Cells[id].ConfigDir)
	}
	return out
}

var (
	// ErrNoHomes: the table declares no cwd_home at all (it predates the key).
	ErrNoHomes = errors.New("no cell declares cwd_home")
	// ErrNoHome: the directory is under no cell's cwd_home.
	ErrNoHome = errors.New("under no cell's home")
)

// AmbiguousHomeError: cells of different scopes declare the same home, and it
// is the longest one containing the directory.
type AmbiguousHomeError struct {
	Home  string
	Cells []string
}

func (e *AmbiguousHomeError) Error() string {
	return fmt.Sprintf("cells %s of different scopes share the home %s", strings.Join(e.Cells, ","), e.Home)
}

// Home is the longest cwd_home containing a directory, with its scope and the
// cells declaring it.
type Home struct {
	Path  string
	Scope string
	Cells []string
}

func realClean(p string) string {
	if r, err := filepath.EvalSymlinks(p); err == nil {
		return filepath.Clean(r)
	}
	return filepath.Clean(p)
}

func within(dir, home string) bool {
	return dir == home || strings.HasPrefix(dir, home+string(filepath.Separator))
}

// HasHomes reports whether any cell declares a cwd_home.
func (t *Table) HasHomes() bool {
	if t == nil {
		return false
	}
	for _, c := range t.Cells {
		if c.CwdHome != "" {
			return true
		}
	}
	return false
}

// HomeFor returns the longest cwd_home containing dir (both sides cleaned and
// symlink-resolved, compared on path-segment boundaries).
func (t *Table) HomeFor(dir string) (Home, error) {
	if !t.HasHomes() {
		return Home{}, ErrNoHomes
	}
	d := realClean(expandHome(dir))
	best := ""
	byHome := map[string][]Cell{}
	for _, c := range t.Cells {
		if c.CwdHome == "" {
			continue
		}
		h := realClean(c.CwdHome)
		if !within(d, h) {
			continue
		}
		byHome[h] = append(byHome[h], c)
		if len(h) > len(best) {
			best = h
		}
	}
	if best == "" {
		return Home{}, ErrNoHome
	}
	cells := byHome[best]
	ids := make([]string, 0, len(cells))
	sc := cells[0].Scope
	mixed := false
	for _, c := range cells {
		ids = append(ids, c.ID)
		if c.Scope != sc {
			mixed = true
		}
	}
	sort.Strings(ids)
	if mixed {
		return Home{}, &AmbiguousHomeError{Home: best, Cells: ids}
	}
	return Home{Path: best, Scope: sc, Cells: ids}, nil
}

// SameAccountIn lists the cells of scope (canonical) whose account letter is
// account, first declared first (rank; a cell without rank last), then by id.
func (t *Table) SameAccountIn(account, sc string) []Cell {
	if t == nil || account == "" {
		return nil
	}
	want := string(scope.Canonical(sc))
	var out []Cell
	for _, c := range t.Cells {
		if c.Account == account && c.Scope == want {
			out = append(out, c)
		}
	}
	sort.Slice(out, func(i, j int) bool {
		ri, rj := out[i].Rank, out[j].Rank
		switch {
		case ri != nil && rj != nil && *ri != *rj:
			return *ri < *rj
		case (ri == nil) != (rj == nil):
			return ri != nil
		}
		return out[i].ID < out[j].ID
	})
	return out
}

// IDs lists every cell id, sorted.
func (t *Table) IDs() []string { return t.idsWhere(func(Cell) bool { return true }) }

// IDsInScope lists the ids of the cells of scope (canonical), sorted.
func (t *Table) IDsInScope(sc string) []string {
	want := string(scope.Canonical(sc))
	return t.idsWhere(func(c Cell) bool { return c.Scope == want })
}

func (t *Table) idsWhere(keep func(Cell) bool) []string {
	if t == nil {
		return nil
	}
	var ids []string
	for id, c := range t.Cells {
		if keep(c) {
			ids = append(ids, id)
		}
	}
	sort.Strings(ids)
	return ids
}

// expandHome resolves a leading ~ against the user's home dir.
func expandHome(p string) string {
	if !strings.HasPrefix(p, "~") {
		return p
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return p
	}
	return filepath.Join(home, strings.TrimPrefix(p, "~"))
}
