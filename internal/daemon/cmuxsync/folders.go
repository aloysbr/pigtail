// Folder arrangement (sub_x000000000000041, D2, D3, D6): one cmux group per
// space, then « Inbox » and « Standby »; inside a folder the gravest
// session first, Standby never sorted. Arrange is pure and returns one round:
// the runner applies it only while the cmux window is not key (D2) and lists
// cmux again before the next round, so group ids are always read, never guessed.

// FolderOpKind is one folder write.
type FolderOpKind string

const (
	FolderDissolve FolderOpKind = "dissolve" // ungroup a group pigtail does not own; members kept
	FolderCreate   FolderOpKind = "create"   // anchor-only folder, anchor generated by cmux
	FolderAdd      FolderOpKind = "add"
	FolderRemove   FolderOpKind = "remove"   // P2 (b) only: out of its group, kept open, just before its FolderAdd
	FolderSetIcon  FolderOpKind = "set-icon" // D11, own folders only
	FolderRename   FolderOpKind = "rename"   // lot 6: the former no-subject folder, renamed in place (P20)
	FolderDelete   FolderOpKind = "delete"   // an own folder left with its anchor only, that anchor bare (spec 3)
	FolderMove     FolderOpKind = "move"     // P4b only: an own folder block after (before) Ref
	FolderReorder  FolderOpKind = "reorder"  // sorted only: the whole window
	FolderPlace    FolderOpKind = "place"    // NoSort only (D39): Workspace right after (before) Ref, a member of the same own folder
	// Emitted by ToggleFolders only (D12), never by Arrange: the arrangement
	// does not fold or unfold an existing folder.
	FolderCollapse FolderOpKind = "collapse"
	FolderExpand   FolderOpKind = "expand"
)

// FolderOp is one write of a round.
type FolderOp struct {
	Kind         FolderOpKind
	Group        string   // dissolve, add, delete, move (an own folder only)
	Ref          string   // move, create: the group it goes after, or before when Before; place: the workspace of the same folder
	RefFolder    string   // create: the folder created earlier in the same round it goes after
	Before       bool     // move, create, place
	Name         string   // create, rename
	Workspace    string   // add, remove, place
	Icon         string   // create, set-icon: SF Symbol (D11)
	RemoveAnchor bool     // dissolve: its generated anchor is all that is left, bare, and D18 (A) allows it
	Collapse     bool     // create: born collapsed
	Order        []string // reorder: the whole window
}

// ArrangeInput is the window as cmux lists it and what pigtail wants of it.
type ArrangeInput struct {
	Folders  []string          // folder order, D6 (space.Table.FolderOrder)
	Order    []string          // the window's workspaces, display order
	Groups   []cmux.Group      // the window's groups
	Target   map[string]string // workspace → folder; absent = not filed
	Icons    map[string]string // folder → SF Symbol (D11); "" = leave cmux's
	Rank     map[string]int    // workspace → gravity rank, lower first; absent = last
	Unsorted map[string]bool   // folders kept in their order (Standby, D4)
	Collapse map[string]bool   // folders born collapsed
	Pinned   map[string]bool   // pinned workspaces (D13); a pinned group is Group.Pinned
	// Closable holds the generated anchors the runner proved bare (no
	// session, no link, one surface, shell at its prompt); absent = keep it
	// open (spec 3). No anchor is ever closed without it.
	Closable map[string]bool
	// GroupMoves is !cmux.ReorderMovesGroups (P4b): blocks are placed by
	// FolderMove before any reorder.
	GroupMoves bool
	// AddNeedsRemove is !cmux.AddMovesFromGroup (P2 (b)): `add` does not move a
	// workspace out of its group, so R3 removes it first.
	AddNeedsRemove bool
	// AnchorHosts holds the generated anchors that host a session (registry
	// row or subject binding; doubt = hosted), computed by the runner. Such a
	// group is never an own folder (splitGroups): it is foreign, dissolved
	// with its anchor kept, and the anchor is filed like any workspace.
	AnchorHosts map[string]bool
	// CloseEmptyGeneratedAnchors: the runner passes the constant below.
	CloseEmptyGeneratedAnchors bool
	// Selected is the window's selected workspace (list-windows
	// selected_workspace_id), "" when unknown. D21 B: never added to a
	// collapsed folder (R3b).
	Selected string
	// Hold holds the workspaces kept exactly where they are (D40): the young
	// ones, targeted or not. desiredOrder holds only those that are free and
	// not placed by the pinned or folder loops (Hold[ws] && !placed[ws]);
	// absent = arranged normally.
	Hold map[string]bool
	// NoSort is pigtaild --cmux-folder-sort=false (sub_x000000000000030, D5-A):
	// the arrangement files and never sorts — no R5 (no FolderMove, no
	// FolderReorder) — and a created folder is placed by createPlaceKeep (D2,
	// D4) instead of createPlace (D6). The bands and the entering tabs move
	// one tab at a time (FolderPlace, D39 of sub_x000000000000014): never a
	// whole-window reorder, which lifts a folder holding a pinned member
	// (cmux probe P26 a). Zero = sorted, as before.
	NoSort bool
	// Enter holds the workspaces entering their place (D16 of
	// sub_x000000000000014): pigtail's add not yet seen at the bottom (D11 (A)
	// of sub_x000000000000030: cmux's add keeps the side a workspace comes
	// from, cmux probe P19), a band change, an unpin. Each goes to the bottom of
	// its band, or of its folder when the folder has no bands. Ignored when
	// sorted. Replaces Tail.
	Enter map[string]bool
	// Band holds a bound workspace's maturity band (BandOf of its subject's
	// status); absent = no band, under the bands (D15).
	Band map[string]int
	// Banded holds the folders sorted in bands (D14): the area folders and
	// « Inbox », never « Standby » nor a focus.
	Banded map[string]bool
	// Bound holds the workspaces bound to a subject (Filing.Bound); one absent
	// keeps its slot in a banded folder (D15, D20).
	Bound map[string]bool
	// Last holds the off-topic workspaces filed in a space (D1 of
	// sub_x000000000000019): sorted after the other free members of their
	// folder. Ignored with NoSort, where « last » is #218's bottom-of-folder
	// placement (Enter).
	Last map[string]bool
}

// CloseEmptyGeneratedAnchors is D18 (A), decided by the user: the generated
// anchor left alone in a dissolved foreign group (the manual groups at
// rollout, a D9 group later) is closed. Only a Closable (proved bare) anchor
// goes; any other stays and the runner files it in « Inbox » (D7).
const CloseEmptyGeneratedAnchors = true

// Arrange returns the first non-empty round of R1–R5, nil once arranged.
func Arrange(in ArrangeInput) []FolderOp {
	own, foreign := splitGroups(in)
	if pairStale(in, own) {
		return nil // skip the round, the runner re-reads cmux
	}
	groupOf := map[string]string{}
	for _, gr := range in.Groups {
		for _, m := range gr.Members {
			groupOf[m] = gr.ID
		}
	}
	var ops []FolderOp
	if op, ok := renameFormer(in, foreign); ok { // lot 6: FormerNoSubject → NoSubject, in place
		return []FolderOp{op}
	}
	for _, gr := range foreign { // R1
		if _, filed := in.Target[gr.AnchorID]; filed {
			ops = append(ops, FolderOp{Kind: FolderDissolve, Group: gr.ID})
		}
	}
	if len(ops) > 0 {
		return ops
	}
	// R3b (D21 B, cmux probe P2b/P2c): only the add of the window's selected
	// workspace expands a collapsed group, so that workspace is never added to
	// a collapsed folder, nor wants a folder born collapsed; it stays where it
	// is and is filed at a later round, once it is no longer selected.
	deferred := func(ws, f string) bool { return deferredAdd(in, own, ws, f) }
	wanted := map[string]bool{}
	for _, ws := range in.Order {
		if f, ok := in.Target[ws]; ok && !deferred(ws, f) {
			wanted[f] = true
		}
	}
	atEnd := ""                    // NoSort: the last folder created at the end in this round
	for _, f := range in.Folders { // R2
		if wanted[f] && own[f] == nil {
			op := FolderOp{Kind: FolderCreate, Name: f, Icon: in.Icons[f], Collapse: in.Collapse[f]}
			if in.NoSort {
				var end bool
				op.Ref, op.RefFolder, op.Before, end = createPlaceKeep(in, own, atEnd, f)
				if end {
					atEnd = f
				}
			} else {
				op.Ref, op.RefFolder, op.Before = createPlace(in, own, wanted, f)
			}
			ops = append(ops, op)
		}
	}
	if len(ops) > 0 {
		return ops
	}
	for _, ws := range in.Order { // R3
		f, ok := in.Target[ws]
		if gr := own[f]; ok && gr != nil && groupOf[ws] != gr.ID && !deferred(ws, f) {
			if in.AddNeedsRemove && groupOf[ws] != "" { // P2 (b): add does not move
				ops = append(ops, FolderOp{Kind: FolderRemove, Workspace: ws})
			}
			ops = append(ops, FolderOp{Kind: FolderAdd, Group: gr.ID, Workspace: ws})
		}
	}
	for _, f := range in.Folders { // R3, icons (D11)
		if gr, want := own[f], in.Icons[f]; gr != nil && want != "" && gr.Icon != want {
			ops = append(ops, FolderOp{Kind: FolderSetIcon, Group: gr.ID, Icon: want})
		}
	}
	if len(ops) > 0 {
		return ops
	}
	for _, gr := range foreign { // R4 (D3, D9; D18 (A) for the anchor)
		remove := in.CloseEmptyGeneratedAnchors && gr.AnchorGenerated && len(gr.Members) == 1 && in.Closable[gr.AnchorID]
		ops = append(ops, FolderOp{Kind: FolderDissolve, Group: gr.ID, RemoveAnchor: remove})
	}
	for _, f := range in.Folders { // spec 2: an empty folder goes; spec 3: its anchor only when bare
		gr := own[f]
		if gr == nil || len(gr.Members) != 1 {
			continue
		}
		if in.Closable[gr.AnchorID] {
			ops = append(ops, FolderOp{Kind: FolderDelete, Group: gr.ID})
		} else {
			ops = append(ops, FolderOp{Kind: FolderDissolve, Group: gr.ID}) // anchor kept, filed next round (D7)
		}
	}
	if len(ops) > 0 {
		return ops
	}
	if in.NoSort { // D5-A: filed, never sorted — no R5; only the bands and the entering tabs move (D2, D16), one at a time (D39)
		if ops := noSortPlaces(in, own); len(ops) > 0 {
			return ops
		}
		return nil
	}
	if in.GroupMoves { // R5, P4b: blocks first
		if ops := folderMoves(in, own); len(ops) > 0 {
			return ops
		}
	}
	if want := desiredOrder(in, own); !slices.Equal(want, in.Order) { // R5
		return []FolderOp{{Kind: FolderReorder, Order: want}}
	}
	return nil
}

// createPlace is where a created folder goes, in its creation round (D6):
// cmux creates a group at the top of the window (cmux probe P11), and the
// reorder that fixes it comes rounds later, after ArrangeSettle and only while
// cmux is not key; a folder left on top meanwhile would sit above the folders
// preceding it. The folder goes right after the closest folder preceding it in
// D6 order, existing (ref) or created earlier in this round (refFolder); with
// none, before the first existing own folder; with none either, after the last
// pinned group (D13); else nowhere (it is alone). Relative to a group, never by
// index (P4b).
func createPlace(in ArrangeInput, own map[string]*cmux.Group, wanted map[string]bool, f string) (ref, refFolder string, before bool) {
	i := slices.Index(in.Folders, f)
	for j := i - 1; j >= 0; j-- {
		p := in.Folders[j]
		if gr := own[p]; gr != nil {
			return gr.ID, "", false
		}
		if wanted[p] {
			return "", p, false
		}
	}
	for _, n := range in.Folders[i+1:] {
		if gr := own[n]; gr != nil {
			return gr.ID, "", true
		}
	}
	pinned := map[string]string{}
	for _, gr := range in.Groups {
		if gr.Pinned {
			pinned[gr.AnchorID] = gr.ID
		}
	}
	for _, ws := range in.Order {
		if id, ok := pinned[ws]; ok {
			ref = id
		}
	}
	return ref, "", false
}

// createPlaceKeep is where a created folder goes without the sort (D2, D4, D7
// of sub_x000000000000030): right before « Inbox » where it stands now;
// without « Inbox », and always for « Standby », at the end — after the
// folder created at the end earlier in this round (prev), else after the last
// own folder or pinned group block of the window; with none, nowhere (cmux
// leaves it on top, cmux probe P11; T1 of the plan). « Standby » is born after
// the last block, like a new folder without « Inbox » (D7: « at the end »
// = after the last block, D4's « last » included). end says it went to the
// end. Relative to a group, never by index (P4b).
func createPlaceKeep(in ArrangeInput, own map[string]*cmux.Group, prev, f string) (ref, refFolder string, before, end bool) {
	if f == space.MacMaintenance {
		// G1: just above « Standby » when it exists, else it falls to the end
		// of the block like « Standby » does (« Standby » is later created
		// after it).
		if gr := own[space.Standby]; gr != nil {
			return gr.ID, "", true, false
		}
	}
	if gr := own[space.NoSubject]; gr != nil && f != space.Standby && f != space.MacMaintenance {
		return gr.ID, "", true, false
	}
	if prev != "" {
		return "", prev, false, true
	}
	block := map[string]string{} // anchor → group id: own folders and pinned groups
	for _, gr := range in.Groups {
		if o := own[gr.Name]; gr.Pinned || (o != nil && o.ID == gr.ID) {
			block[gr.AnchorID] = gr.ID
		}
	}
	for _, ws := range in.Order {
		if id, ok := block[ws]; ok {
			ref = id
		}
	}
	return ref, "", false, true
}

// folderMoves places own folder blocks after the pinned groups, in D6 order,
// moving own folders only (D13), relative to a group, never by index (P4b).
func folderMoves(in ArrangeInput, own map[string]*cmux.Group) []FolderOp {
	isOwn, anchorOf := map[string]bool{}, map[string]string{}
	var want []string
	for _, gr := range in.Groups {
		if gr.Pinned {
			anchorOf[gr.AnchorID] = gr.ID
		}
	}
	for _, f := range in.Folders {
		if gr := own[f]; gr != nil {
			anchorOf[gr.AnchorID], isOwn[gr.ID] = gr.ID, true
		}
	}
	var cur []string
	for _, ws := range in.Order {
		if id, ok := anchorOf[ws]; ok {
			cur = append(cur, id)
		}
	}
	for _, id := range cur { // pinned groups, current order
		if !isOwn[id] {
			want = append(want, id)
		}
	}
	for _, f := range in.Folders {
		if gr := own[f]; gr != nil {
			want = append(want, gr.ID)
		}
	}
	var ops []FolderOp
	place := func(id, ref string, before bool) {
		ops = append(ops, FolderOp{Kind: FolderMove, Group: id, Ref: ref, Before: before})
		cur = slices.DeleteFunc(cur, func(x string) bool { return x == id })
		i := slices.Index(cur, ref)
		if !before {
			i++
		}
		cur = slices.Insert(cur, i, id)
	}
	if len(want) > 0 && isOwn[want[0]] && cur[0] != want[0] {
		place(want[0], cur[0], true)
	}
	for i := 1; i < len(want); i++ {
		if !isOwn[want[i]] {
			continue
		}
		if j := slices.Index(cur, want[i-1]); j+1 >= len(cur) || cur[j+1] != want[i] {
			place(want[i], want[i-1], false)
		}
	}
	return ops
}

// Names are compared byte for byte, on purpose: no Unicode normalisation (P11).
// A name cmux hands back differently is caught by the runner right after the
// create (applyFolderOp), not absorbed here.
// deferredAdd is R3b: ws is the window's selected workspace and folder f is
// collapsed, or would be born collapsed.
func deferredAdd(in ArrangeInput, own map[string]*cmux.Group, ws, f string) bool {
	if in.Selected == "" || ws != in.Selected {
		return false
	}
	if gr := own[f]; gr != nil {
		return gr.Collapsed
	}
	return in.Collapse[f]
}

// deferredSelected: the round leaves the selected workspace out of the
// collapsed folder it targets (R3b), so a round with no op still waits (D3 of
// sub_x000000000000019, the selected-collapsed wait).
func deferredSelected(in ArrangeInput) bool {
	f, ok := in.Target[in.Selected]
	if in.Selected == "" || !ok {
		return false
	}
	own, _ := splitGroups(in)
	if gr := own[f]; gr != nil && slices.Contains(gr.Members, in.Selected) {
		return false
	}
	return deferredAdd(in, own, in.Selected, f)
}

// renameFormer renames, in place, the folder pigtail made under the former
// no-subject name (space.FormerNoSubject): a rename keeps the folder's place,
// members, fold and icon (cmux probe P20a), where the merge (R2–R4) would create
// the new folder elsewhere — at the end without the sort (createPlaceKeep).
// Only a group pigtail could have owned: generated anchor hosting no session,
// not pinned (splitGroups put it in foreign). Nothing when a group already
// carries the current name (P20d: cmux accepts a duplicate) or when two former
// ones are listed: the merge path converges them.
func renameFormer(in ArrangeInput, foreign []cmux.Group) (FolderOp, bool) {
	if !slices.Contains(in.Folders, space.NoSubject) {
		return FolderOp{}, false
	}
	for _, gr := range in.Groups {
		if gr.Name == space.NoSubject {
			return FolderOp{}, false
		}
	}
	var found []cmux.Group
	for _, gr := range foreign {
		if gr.Name == space.FormerNoSubject && gr.AnchorGenerated && !in.AnchorHosts[gr.AnchorID] {
			found = append(found, gr)
		}
	}
	if len(found) != 1 {
		return FolderOp{}, false
	}
	return FolderOp{Kind: FolderRename, Group: found[0].ID, Name: space.NoSubject}, true
}

// pairStale: Order (ListWorkspaces) and Groups (ListGroups) are two reads; a
// pinned group or an own folder whose anchor Order does not show means they
// do not match. Arrange skips the round on it (a stale pair must not reach
// folderMoves: cur empty, Index -1 panic), the space drag judge judges nothing
// (stalePair, space_drag.go).
func pairStale(in ArrangeInput, own map[string]*cmux.Group) bool {
	inOrder := make(map[string]bool, len(in.Order))
	for _, ws := range in.Order {
		inOrder[ws] = true
	}
	for _, gr := range in.Groups {
		if o := own[gr.Name]; (gr.Pinned || (o != nil && o.ID == gr.ID)) && !inOrder[gr.AnchorID] {
			return true
		}
	}
	return false
}

func splitGroups(in ArrangeInput) (map[string]*cmux.Group, []cmux.Group) {
	own := map[string]*cmux.Group{}
	var foreign []cmux.Group
	for i := range in.Groups {
		gr := &in.Groups[i]
		if gr.Pinned { // D13: neither a folder nor foreign, never touched
			continue
		}
		if gr.AnchorGenerated && !in.AnchorHosts[gr.AnchorID] && slices.Contains(in.Folders, gr.Name) && own[gr.Name] == nil {
			own[gr.Name] = gr
			continue
		}
		foreign = append(foreign, *gr)
	}
	return own, foreign
}

func desiredOrder(in ArrangeInput, own map[string]*cmux.Group) []string {
	placed := map[string]bool{}
	var out []string
	pinnedGroup := map[string]bool{}
	for _, gr := range in.Groups { // D13: pinned groups, then pinned workspaces, on top, unsorted
		if gr.Pinned {
			for _, m := range gr.Members {
				pinnedGroup[m] = true
			}
		}
	}
	inOwn := map[string]bool{}
	for _, gr := range own {
		for _, m := range gr.Members {
			inOwn[m] = true
		}
	}
	for _, ws := range in.Order {
		// A pinned member of an own folder is not lifted on top: cmux keeps it
		// in its block (cmux probe P10a) and hands it back there on reorder.
		if pinnedGroup[ws] || (in.Pinned[ws] && !inOwn[ws]) {
			out = append(out, ws)
			placed[ws] = true
		}
	}
	nPinned := len(out)
	for _, f := range in.Folders {
		gr := own[f]
		if gr == nil {
			continue
		}
		if !placed[gr.AnchorID] {
			out = append(out, gr.AnchorID)
			placed[gr.AnchorID] = true
		}
		ms := slices.DeleteFunc(slices.Clone(gr.Members), func(m string) bool { return m == gr.AnchorID })
		ms = blockMembers(in, f, ms, true) // pinned members keep their slot (P10); bands (D2)
		for _, m := range ms {
			if placed[m] { // never twice: a duplicate makes Reorder refuse (ErrInvalidArg)
				continue
			}
			out = append(out, m)
			placed[m] = true
		}
	}
	held := map[string]bool{} // D40: free, young, kept in their slot
	for _, ws := range in.Order {
		if in.Hold[ws] && !placed[ws] {
			held[ws] = true
		}
	}
	for _, ws := range in.Order { // not filed (D7: only a dissolving group's anchor; pinned ones, D13, are emitted first): current order, after the folders
		if !placed[ws] && !held[ws] {
			out = append(out, ws)
		}
	}
	if len(held) == 0 {
		return out
	}
	return insertHeld(in, own, out, held, nPinned)
}

// insertHeld puts each held workspace, in Order order, right after the one
// that precedes it in Order: after the last element of that one's block when
// it belongs to a listed group (own folder or pinned group), after it when it
// is free, pinned or itself held, at the head of the non-pinned when nothing
// precedes it (D40). Never inside a block: cmux would hand the member back to
// its block (cmux probe P10a).
func insertHeld(in ArrangeInput, own map[string]*cmux.Group, out []string, held map[string]bool, nPinned int) []string {
	blockOf := map[string]*cmux.Group{}
	for i := range in.Groups {
		gr := &in.Groups[i]
		if gr.Pinned || own[gr.Name] != nil && own[gr.Name].ID == gr.ID {
			for _, m := range gr.Members {
				blockOf[m] = gr
			}
		}
	}
	for i, ws := range in.Order {
		if !held[ws] {
			continue
		}
		at := nPinned
		if i > 0 {
			p := in.Order[i-1]
			at = slices.Index(out, p) + 1
			if gr := blockOf[p]; gr != nil {
				for j, o := range out {
					if slices.Contains(gr.Members, o) && j+1 > at {
						at = j + 1
					}
				}
			}
		}
		out = slices.Insert(out, at, ws)
	}
	return out
}
