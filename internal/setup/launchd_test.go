// The refusal is a dead end unless it says how to get out of it: `pigtail
// setup` aborts before the completions and the daemon check, and has no
// --force.
func TestReadPlistTuning_refusalSaysWhatToDo(t *testing.T) {
	path := filepath.Join(t.TempDir(), "unknown-flag.plist")
	body := `<?xml version="1.0" encoding="UTF-8"?>
<plist version="1.0">
<dict>
  <key>ProgramArguments</key>
  <array>
    <string>/p/pigtaild</string>
    <string>-some-future-flag</string>
    <string>42</string>
  </array>
</dict>
</plist>
`
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
	_, err := ReadPlistTuning(path)
	if err == nil {
		t.Fatal("an unrecognised flag must still fail loudly")
	}
	msg := err.Error()
	for _, want := range []string{"--some-future-flag", path, "delete the file"} {
		if !strings.Contains(msg, want) {
			t.Errorf("refusal should mention %q, got: %s", want, msg)
		}
	}
}

// TestPreserveTuningCarriesClassLimits guards the trap this repo has already
// paid for twice (-db-offsite-dir, then the -ram-* family): a flag the
// template cannot emit is silently erased by the next `pigtail setup`. A
// class limit set by hand must survive, repeats included.
func TestPreserveTuningCarriesClassLimits(t *testing.T) {
	existing := filepath.Join(t.TempDir(), "sh.pigtail.daemon.plist")
	handTuned, err := GeneratePlist(PlistParams{
		PigtaildPath:     "/old/pigtaild",
		ConfigDir:        "/old/config",
		Path:             "/old/bin",
		AdmitClassLimits: []string{"vitest-browser:1", "jest:2"},
	})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(handTuned, "vitest-browser:1") || !strings.Contains(handTuned, "jest:2") {
		t.Fatalf("the template dropped a class limit:\n%s", handTuned)
	}
	if err := os.WriteFile(existing, []byte(handTuned), 0o644); err != nil {
		t.Fatal(err)
	}

	merged, err := PreserveTuning(existing, PlistParams{
		PigtaildPath: "/new/pigtaild", ConfigDir: "/new/config", Path: "/new/bin",
	})
	if err != nil {
		t.Fatalf("PreserveTuning: %v", err)
	}
	regenerated, err := GeneratePlist(merged)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"--admit-class-limit", "vitest-browser:1", "jest:2"} {
		if !strings.Contains(regenerated, want) {
			t.Fatalf("a setup rerun dropped %q:\n%s", want, regenerated)
		}
	}
}
