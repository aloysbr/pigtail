// The plist under test carries BOTH the primary off-site destination and
// the fallback destination, and both assertions below run in the same
// test — not because the primary needs its own new coverage (it already has
// one, in TestPreserveTuningSurvivesASetupRerun), but because a regression
// that overwrites one field while leaving the other alone (e.g. a
// WithTuningFrom branch that assigns unconditionally instead of behind its
// own "if t.X != ..." check) would only show up when both are asserted
// together in the same preserve-then-regenerate cycle. Asserting only the
// new flag, as an earlier version of this test did, would pass even if the
// primary destination were silently dropped alongside it.
func TestPreserveTuning_carriesBothOffsiteDestinationsTogether(t *testing.T) {
	existing := filepath.Join(t.TempDir(), "sh.pigtail.daemon.plist")
	handTuned, err := GeneratePlist(PlistParams{
		PigtaildPath:          "/old/pigtaild",
		ConfigDir:             "/old/config",
		Path:                  "/old/bin",
		DBOffsiteDir:          "backup-host:/srv/backups/pigtail-backups",
		DBOffsiteFallbackDest: "backup-host-ssh",
	})
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(existing, []byte(handTuned), 0o644); err != nil {
		t.Fatal(err)
	}

	merged, err := PreserveTuning(existing, PlistParams{
		PigtaildPath: "/new/pigtaild", ConfigDir: "/new/config", Path: "/new/bin",
	})
	if err != nil {
		t.Fatalf("PreserveTuning: %v", err)
	}
	regenerated, err := GeneratePlist(merged)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(regenerated, flagPair("--db-offsite-dir", "backup-host:/srv/backups/pigtail-backups")) {
		t.Errorf("a re-run of setup lost the hand-tuned --db-offsite-dir:\n%s", regenerated)
	}
	if !strings.Contains(regenerated, flagPair("--db-offsite-fallback-dest", "backup-host-ssh")) {
		t.Errorf("a re-run of setup lost the hand-tuned --db-offsite-fallback-dest:\n%s", regenerated)
	}
}

// This is the test the whole task exists for: a plist that carries
