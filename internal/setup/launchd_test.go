// --- read-back -------------------------------------------------------------
//
// The template carrying a flag is not enough: `pigtail setup` regenerates
// the plist from scratch every time, so unless something reads the *old*
// plist's values back into PlistParams before regenerating, every one of
// the flags above still resets to the deployment default (or is dropped,
// for the three with no default) on a second run. That was the actual bug
// behind the 2026-09-08 regression report — the template alone only fixes
// it "in principle". ReadPlistTuning + PreserveTuning below is what closes
// it for real; the tests exercise the composition end to end, not the
// parser in isolation, because the missing wiring — not a parsing bug — is
// exactly what a parser-only test would fail to catch.

func TestReadPlistTuning_missingFileReturnsZeroValueNotError(t *testing.T) {
	got, err := ReadPlistTuning(filepath.Join(t.TempDir(), "does-not-exist.plist"))
	if err != nil {
		t.Fatalf("missing plist should not be an error (first-ever setup): %v", err)
	}
	if !reflect.DeepEqual(got, PlistParams{}) {
		t.Fatalf("missing plist should read back as zero PlistParams, got %+v", got)
	}
}

