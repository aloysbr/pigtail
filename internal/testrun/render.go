package testrun

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

// GeneratedConfigName is what pigtail writes next to the installed client.
const GeneratedConfigName = "vitest.pigtail.config.mjs"

// RenderVitestConfig writes the wrapper config that imports the repo's own and
// adds exactly two things: the CPU slot setup file, and a ceiling on every
// pool vitest could run under.
//
// The ceiling is min(what the repo asked for, the budget) — never the budget
// alone. See [MinCeiling] for why that distinction is the whole point of this
// function.
//
// maxWorkers is not enough on its own: vitest resolves a pool's actual size as
// poolOptions.<pool>.max{Forks,Threads} ?? maxWorkers, so a repo config that
// sets poolOptions directly (forks, threads, vmForks or vmThreads — whichever
// pool it runs under) would bypass a maxWorkers-only cap entirely. Capping all
// four leaves the run capped whichever pool wins, and costs nothing on the
// pools not in use. Each pool falls back to the *effective* maxWorkers rather
// than to the budget, so a repo that pinned only maxWorkers still has its pin
// respected by every pool.
//
// Lowering ceilings is not enough either: a repo that pinned its own pool
// *minimum* (test.minWorkers, poolOptions.<pool>.minForks / minThreads) —
// precisely the repo that already tuned its pool, i.e. this command's audience
// — would end up with min > max, and tinypool throws a RangeError at startup
// before a single test runs. So the same block clamps every minimum down to
// the effective ceiling.
//
// setupFiles is assigned after mergeConfig rather than passed through it:
// mergeConfig concatenates arrays, so routing it through the merge would add
// the base repo's own setup files a second time.
// An empty setupFile renders a wrapper that takes no CPU slot at all — the
// GrainRun case (a browser-mode run). The wrapper is still worth writing:
// it carries the ceiling and the write-back. What it must not do is push an
// empty string into setupFiles, which vitest would try to load.
func RenderVitestConfig(dir, baseConfig, setupFile string, budget int) (string, error) {
	addSetup := "  // pigtail: no slot setup for this run (arbitrated as a whole).\n"
	if setupFile != "" {
		addSetup = "  setupFiles.push(" + jsString(setupFile) + ");\n"
	}
	body := `// Generated by ` + "`pigtail test`" + ` — do not edit, do not commit.
import os from 'node:os';
import { mergeConfig } from 'vitest/config';

import base from ` + jsString(baseConfig) + `;

export default async (env) => {
  const resolved = await (typeof base === 'function' ? base(env) : base);
  const previous = resolved && resolved.test ? resolved.test.setupFiles : undefined;
  const setupFiles = [...(Array.isArray(previous) ? previous : previous ? [previous] : [])];
` + addSetup + `
  // The ceilings are NOT passed through mergeConfig: it overwrites scalars
  // from its second argument, which would replace a ceiling the repo pinned
  // on purpose with the machine budget — raising it, not lowering it.
  const merged = mergeConfig(resolved, {});
  ` + ceilingHelperJS(budget) + `
  const test = merged.test || (merged.test = {});
  const pools = test.poolOptions || (test.poolOptions = {});

  // The effective ceiling: the budget, unless the repo asked for less.
  const ceiling = minCeiling(test.maxWorkers);
  test.maxWorkers = ceiling;

  // Vitest resolves a pool's size as poolOptions.<pool>.max* ?? maxWorkers,
  // so a repo that sets poolOptions directly would escape a maxWorkers-only
  // cap. Each pool therefore falls back to the *effective ceiling*, never to
  // the budget — otherwise a repo that pinned only maxWorkers would see its
  // pin respected there and bypassed in every pool.
  const capPool = (pool, key) => {
    const holder = pools[pool] || (pools[pool] = {});
    holder[key] = Math.min(asCount(holder[key]) ?? ceiling, ceiling);
  };
  capPool('forks', 'maxForks');
  capPool('threads', 'maxThreads');
  capPool('vmForks', 'maxForks');
  capPool('vmThreads', 'maxThreads');

  // A repo that pinned a pool *minimum* above the effective ceiling would
  // leave min > max, and tinypool throws a RangeError at startup before a
  // single test runs — the arbiter must never be the reason tests do not run.
  const clampMin = (holder, key) => {
    if (!holder || typeof holder !== 'object') return;
    const value = asCount(holder[key]);
    if (value !== null && value > ceiling) holder[key] = ceiling;
  };
  clampMin(test, 'minWorkers');
  clampMin(test, 'minForks');
  clampMin(test, 'minThreads');
  clampMin(pools.forks, 'minForks');
  clampMin(pools.threads, 'minThreads');
  clampMin(pools.vmForks, 'minForks');
  clampMin(pools.vmThreads, 'minThreads');
  merged.test = { ...merged.test, setupFiles };
  ` + writeBackJS(resolvedPath(dir, baseConfig), baseConfig) + `
  return merged;
};
`
	path := filepath.Join(dir, GeneratedConfigName)
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil { //nolint:gosec // a config the repo's own tooling reads
		return "", fmt.Errorf("write generated config: %w", err)
	}
	return path, nil
}

// writeBackJS records what the evaluated config turned out to be, for the
// next run to read (see resolvedFacts). It runs inside the wrapper because
// this is the only moment the answer exists.
//
// Everything here is wrapped in a try/catch that swallows: a read-only cache
// directory, a full disk or a config whose file vanished must cost the run
// nothing. The arbiter must never be the reason tests do not run — the same
// invariant the rest of this package serves.
func writeBackJS(factsPath, baseConfig string) string {
	return `try {
    const { writeFileSync, statSync } = await import('node:fs');
    const t = merged.test || {};
    writeFileSync(` + jsString(factsPath) + `, JSON.stringify({
      config: ` + jsString(baseConfig) + `,
      mtime_ms: Math.trunc(statSync(` + jsString(baseConfig) + `).mtimeMs),
      browser: Boolean(t.browser && t.browser.enabled),
      max_workers: typeof ceiling === 'number' ? ceiling : 0,
      isolate: t.isolate !== false,
    }));
  } catch {
    // Diagnostics are never worth failing a test run over.
  }`
}

// jsString renders s as a JS string literal. strconv.Quote produces Go syntax,
// which for these paths is a subset of JS syntax — but the escaping of quotes
// and backslashes is what matters and it is identical.
func jsString(s string) string {
	return strconv.Quote(strings.ReplaceAll(s, "\x00", ""))
}
