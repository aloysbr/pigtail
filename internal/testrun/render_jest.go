package testrun

import (
	"fmt"
	"os"
	"path/filepath"
)

// GeneratedJestConfigName is what pigtail writes next to the installed client.
const GeneratedJestConfigName = "jest.pigtail.config.cjs"

// RenderJestConfig writes the wrapper config that requires the repo's own and
// adds exactly two things: the CPU slot setup file, and a ceiling on the
// workers — the lower of the budget and whatever the repo pinned itself.
//
// Three things it must get right, each of which silently breaks a real repo:
//
//   - rootDir. `jest --config <path>` roots the run at the config file's
//     directory, which here is node_modules/.cache/pigtail. Every
//     `<rootDir>/src/…` in the repo's own config would then point inside the
//     cache. The wrapper pins rootDir back to the original config's directory,
//     and resolves a relative one the repo set against that same directory.
//   - An async config. next/jest's createJestConfig returns a *function*
//     returning a promise, so the wrapper awaits whatever require() hands it.
//   - setupFilesAfterEnv is concatenated, never replaced: dropping the repo's
//     own setup files would take its matchers and polyfills with them.
//
// maxWorkers is set here rather than passed as --maxWorkers on the command
// line for the reason PR A exists: the flag overrides the config, so a repo
// that pinned a low worker count on purpose would be overridden by the machine
// budget. Only a wrapper that reads the repo's value can take the minimum.
func RenderJestConfig(dir, baseConfig, setupFile string, budget int) (string, error) {
	baseDir := filepath.Dir(baseConfig)
	body := `// Generated by ` + "`pigtail test`" + ` — do not edit, do not commit.
const os = require('node:os');
const path = require('node:path');

const base = require(` + jsString(baseConfig) + `);

module.exports = async () => {
  const resolved = await (typeof base === 'function' ? base() : base);
  const cfg = { ...(resolved || {}) };
  ` + ceilingHelperJS(budget) + `
  const previous = cfg.setupFilesAfterEnv;
  cfg.setupFilesAfterEnv = [
    ...(Array.isArray(previous) ? previous : previous ? [previous] : []),
    ` + jsString(setupFile) + `,
  ];

  // --config roots the run at this file's directory. Put it back where the
  // repo's own config lives, or every <rootDir>/… in it points into the cache.
  cfg.rootDir = cfg.rootDir ? path.resolve(` + jsString(baseDir) + `, cfg.rootDir) : ` + jsString(baseDir) + `;

  // ceiling = min(what the repo asked for, the budget) — never the budget alone.
  cfg.maxWorkers = minCeiling(cfg.maxWorkers);
  return cfg;
};
`
	path := filepath.Join(dir, GeneratedJestConfigName)
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil { //nolint:gosec // a config the repo's own tooling reads
		return "", fmt.Errorf("write generated jest config: %w", err)
	}
	return path, nil
}
