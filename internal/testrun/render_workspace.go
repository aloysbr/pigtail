package testrun

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"

	"strings"
)

// RootWorkspaceConfigName is the root wrapper pigtail generates for a
// workspace layout: it carries the machine ceiling and points at one wrapper
// per project.
const RootWorkspaceConfigName = "vitest.pigtail-root.config.mjs"

// RenderWorkspaceConfig writes one wrapper per project plus the root wrapper,
// and returns the root's path along with every file written.
//
// Why a file per project rather than inline `{ extends, test: {...} }` objects
// in one root config — both run, and the inline form is shorter:
//
//	an inline project cannot see what the repo's own config set. It can only
//	overwrite. Measured on vitest 3.2.7 and 4.1.11: inline projects with no
//	name are called "0", "1", "2", and an inline name replaces the repo's own
//	— either way `--project=@app/web` stops matching. A wrapper *imports* the
//	base, so it fills a name in only when there is none, and appends to the
//	repo's setupFiles instead of replacing them.
//
// The ceiling lives on the root wrapper, where it governs the shared pool. Per
// project, a pin is only ever lowered, never added: vitest 4 rejects projects
// that differ in maxWorkers while sharing a sequence.groupOrder, so adding one
// where the repo has none would manufacture a conflict that stops the run.
func RenderWorkspaceConfig(dir, rootBaseConfig string, projects []Project, setupFile string, budget int) (string, []string, error) {
	written, err := renderProjectWrappers(dir, projects, setupFile, budget)
	if err != nil {
		return "", written, err
	}

	rootPath := filepath.Join(dir, RootWorkspaceConfigName)
	body, err := rootWorkspaceBody(rootBaseConfig, written, budget)
	if err != nil {
		return "", written, err
	}
	if werr := os.WriteFile(rootPath, []byte(body), 0o644); werr != nil { //nolint:gosec // a config the repo's own tooling reads
		return "", written, fmt.Errorf("write root config: %w", werr)
	}
	return rootPath, append(written, rootPath), nil
}

// renderProjectWrappers writes one wrapper per project and returns their paths
// in the order vitest should see them.
func renderProjectWrappers(dir string, projects []Project, setupFile string, budget int) ([]string, error) {
	written := make([]string, 0, len(projects))
	for _, p := range projects {
		path := filepath.Join(dir, projectWrapperName(projectSlug(p.Name)))
		if err := os.WriteFile(path, []byte(projectWrapperBody(p, setupFile, budget)), 0o644); err != nil { //nolint:gosec // a config the repo's own tooling reads
			return written, fmt.Errorf("write project config for %s: %w", p.Name, err)
		}
		written = append(written, path)
	}
	return written, nil
}

// projectWrapperBody is the wrapper for one project: the repo's own config,
// plus a root and a name when it has none, plus pigtail's setup file.
func projectWrapperBody(p Project, setupFile string, budget int) string {
	return `// Generated by ` + "`pigtail test`" + ` — do not edit, do not commit.
import os from 'node:os';
import { mergeConfig } from 'vitest/config';

import base from ` + jsString(p.ConfigPath) + `;

export default async (env) => {
  const resolved = await (typeof base === 'function' ? base(env) : base);
  const merged = mergeConfig(resolved, {});
  ` + ceilingHelperJS(budget) + `
  const test = merged.test || (merged.test = {});

  // test.root — NOT the Vite-level "root" — is what roots a project inside a
  // workspace. Measured on vitest 3.2.7 and 4.1.11: with only "root" set, the
  // project stays rooted at this wrapper's directory and the run finds no test
  // file at all, while still reporting success.
  if (!test.root) test.root = merged.root || ` + jsString(p.Root) + `;

  // Only when the repo named nothing: an inline rename would break a
  // --project=<name> filter that already works today.
  if (!test.name) test.name = ` + jsString(p.Name) + `;

  const previous = test.setupFiles;
  test.setupFiles = [
    ...(Array.isArray(previous) ? previous : previous ? [previous] : []),
    ` + jsString(setupFile) + `,
  ];

  // A pin is lowered, never added. Vitest 4 refuses projects that differ in
  // maxWorkers while sharing a sequence.groupOrder, so a ceiling added here
  // where the repo set none would stop the whole run — the root wrapper
  // carries the machine ceiling instead.
  const pin = asCount(test.maxWorkers);
  if (pin !== null && pin > 0) test.maxWorkers = minCeiling(test.maxWorkers);
  ` + clampMinimaJS() + `
  return merged;
};
`
}

// rootWorkspaceBody is the root wrapper: the repo's own root config when it
// has one, the machine ceiling, and the project list.
func rootWorkspaceBody(rootBaseConfig string, projectPaths []string, budget int) (string, error) {
	list, err := json.Marshal(projectPaths)
	if err != nil {
		return "", fmt.Errorf("encode project list: %w", err)
	}

	head := "const resolved = {};\n"
	if rootBaseConfig != "" {
		head = "const resolved = await (typeof base === 'function' ? base(env) : base);\n"
	}
	imports := ""
	if rootBaseConfig != "" {
		imports = "import base from " + jsString(rootBaseConfig) + ";\n"
	}

	return `// Generated by ` + "`pigtail test`" + ` — do not edit, do not commit.
import os from 'node:os';
import { mergeConfig } from 'vitest/config';

` + imports + `
export default async (env) => {
  ` + head + `  const merged = mergeConfig(resolved, {});
  ` + ceilingHelperJS(budget) + `
  const test = merged.test || (merged.test = {});

  // One wrapper per project, each importing the repo's own project config.
  test.projects = ` + string(list) + `;

  // The ceiling governs the pool shared by every project, and is the lower of
  // the budget and whatever this repo pinned at its root.
  const ceiling = minCeiling(test.maxWorkers);
  test.maxWorkers = ceiling;
  const pools = test.poolOptions || (test.poolOptions = {});
  const capPool = (pool, key) => {
    const holder = pools[pool] || (pools[pool] = {});
    holder[key] = Math.min(asCount(holder[key]) ?? ceiling, ceiling);
  };
  capPool('forks', 'maxForks');
  capPool('threads', 'maxThreads');
  capPool('vmForks', 'maxForks');
  capPool('vmThreads', 'maxThreads');
  ` + clampMinimaJS() + `
  return merged;
};
`, nil
}

// clampMinimaJS lowers every pool minimum to the effective ceiling. A repo
// that pinned a minimum above it would leave min > max, and tinypool throws a
// RangeError before a single test runs — the arbiter must never be the reason
// tests do not start.
func clampMinimaJS() string {
	return `const clampMin = (holder, key) => {
    if (!holder || typeof holder !== 'object') return;
    const value = asCount(holder[key]);
    const cap = asCount(test.maxWorkers) ?? minCeiling(null);
    if (value !== null && value > cap) holder[key] = cap;
  };
  clampMin(test, 'minWorkers');
  clampMin(test, 'minForks');
  clampMin(test, 'minThreads');
  clampMin(test.poolOptions && test.poolOptions.forks, 'minForks');
  clampMin(test.poolOptions && test.poolOptions.threads, 'minThreads');
  clampMin(test.poolOptions && test.poolOptions.vmForks, 'minForks');
  clampMin(test.poolOptions && test.poolOptions.vmThreads, 'minThreads');`
}

// projectWrapperName builds a filename vitest 4 accepts as a project config.
//
// Its check is /^vite(?:st)?(?:\.[\w-]+)?\.config\./ — exactly one dotted
// segment between the prefix and "config". "vitest.pigtail.web.config.mjs" has
// two and is refused outright; "vitest.pigtail-web.config.mjs" is not. Vitest 3
// does not check at all, which is what makes this worth a name and a test
// rather than a convention.
func projectWrapperName(slug string) string {
	return "vitest.pigtail-" + slug + ".config.mjs"
}

// projectSlug reduces a project name to the [\w-] the filename check allows.
func projectSlug(name string) string {
	var sb strings.Builder
	lastDash := false
	for _, r := range name {
		switch {
		case r == '_' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9'):
			sb.WriteRune(r)
			lastDash = false
		default:
			if !lastDash && sb.Len() > 0 {
				sb.WriteByte('-')
				lastDash = true
			}
		}
	}
	out := strings.Trim(sb.String(), "-")
	if out == "" {
		return "project"
	}
	return out
}

// describeProjects turns config paths into projects, giving each the name
// vitest itself would use — the package.json name, else the directory — and
// making those names unique, since vitest refuses duplicates.
//
// The name is only a *fallback*: the wrapper uses it when the repo's own
// config names nothing.
func describeProjects(root string, configPaths []string) []Project {
	projects := make([]Project, 0, len(configPaths))
	taken := map[string]bool{}

	for _, cfg := range configPaths {
		dir := filepath.Dir(cfg)
		name := packageName(dir)
		if name == "" {
			name = filepath.Base(dir)
		}
		if taken[name] {
			// apps/web holds both vite.config.ts and vitest.config.ts, and
			// a large monorepo's globs match both: two projects, one directory, one
			// package.json. Distinguish by the config that made them.
			base := strings.TrimSuffix(filepath.Base(cfg), filepath.Ext(cfg))
			name += "-" + base
		}
		for i := 2; taken[name]; i++ {
			name = fmt.Sprintf("%s-%d", name, i)
		}
		taken[name] = true

		projects = append(projects, Project{ConfigPath: cfg, Root: dir, Name: name})
	}
	_ = root
	return projects
}

// packageName reads the "name" field of dir/package.json, or "".
func packageName(dir string) string {
	data, err := os.ReadFile(filepath.Join(dir, "package.json")) //nolint:gosec // inside the worktree
	if err != nil {
		return ""
	}
	var pkg struct {
		Name string `json:"name"`
	}
	if jerr := json.Unmarshal(data, &pkg); jerr != nil {
		return ""
	}
	return pkg.Name
}
